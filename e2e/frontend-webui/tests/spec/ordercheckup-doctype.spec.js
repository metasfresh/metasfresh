/**
 * Bestellkontrolle window ("Order Checkup") — gh32265: surface the resolved C_DocType, read-only,
 * beside the pre-existing DocumentType ("Belegart") ref-list field.
 * AD_Window_ID = 540274, single tab AD_Tab_ID = 540703 (table C_Order_MFGWarehouse_Report).
 *
 * Migration 5825570 adds, purely additively (no DDL, no behaviour change):
 *   * AD_Field 785045 + AD_UI_Element 654787 for C_Order_MFGWarehouse_Report.C_DocType_ID,
 *     IsReadOnly='Y', into the SAME primary AD_UI_ElementGroup (540617) as DocumentType and
 *     directly after it (AD_UI_Element SeqNo 5 -> 6). Grid deliberately left off.
 *
 * ---------------------------------------------------------------------------------------------------
 * TEST-LAYER RATIONALE (metasfresh-test-integrity)
 * ---------------------------------------------------------------------------------------------------
 * This is a desktop-WebUI layout/read-only change, so the faithful primary layer is a frontend-webui
 * Playwright E2E. C_Order_MFGWarehouse_Report rows are generated by OrderCheckupBL — they are NOT
 * created through a window "NEW" action — so the spec does not fabricate one: it provisions a real
 * sales order through the masterdata API and has OrderCheckupBL generate the reports for it, exactly
 * as the product does (see "HOW THE RECORDS UNDER TEST COME INTO EXISTENCE" below). What it proves,
 * all through language-invariant identifiers, run in en_US + de_DE:
 *
 *   (A) window layout — C_DocType_ID sits in the SAME element group as DocumentType and DIRECTLY
 *       after it, i.e. "beside the existing Belegart field".                              [AC1]
 *   (B) record data — the record carries the RIGHT doctype: its C_DocType_ID.value.key resolves to a
 *       C_DocType whose (language-invariant, ref-list) DocBaseType is the one OrderCheckupBuilder
 *       maps this row's DocumentType kind to — Warehouse('WH') -> BKP, Plant('PL') -> BKB — checked
 *       for BOTH kinds, each read back out of the window's own view.                      [AC2]
 *   (C) record data — C_DocType_ID is not editable: readonly=true on the payload the form
 *       renders from.                                                                     [AC1]
 *   (D) UI — the field renders on the detail form (.form-field-C_DocType_ID), is populated, and its
 *       input is disabled, so a user can see but not edit it.                             [AC1]
 *
 * WHAT (C) AND (D) DO — AND DO NOT — PROVE:
 *   The non-editability they observe is DOCUMENT-level, not field-level. OrderCheckupBuilder stamps
 *   Processed=true on every C_Order_MFGWarehouse_Report it generates, and
 *   DocumentReadonly.computeFieldReadonly returns readonly for EVERY field of a processed document
 *   unless that field's column is IsAlwaysUpdateable — no column of this table is. So the payload
 *   `readonly` stays true and the input stays disabled even with the migration's
 *   AD_Field.IsReadOnly flipped from 'Y' to 'N': that flag is belt-and-braces, and this spec does
 *   NOT independently pin it. Every field on this tab is read-only for the same document-level
 *   reason, so the window offers no negative control for it either, and there is no layout-level
 *   substitute to assert instead — the window-layout endpoint carries no field read-only property
 *   at all (no JSONDocumentLayout* DTO has one), and its one adjacent property,
 *   `viewEditorRenderMode`, cannot stand in for one either. It DOES encode field-level read-only —
 *   LayoutFactory returns NEVER whenever the field's `getReadonlyLogicEffective().isConstantTrue()`
 *   (LayoutFactory.java:593-598) — but only ONE-DIRECTIONALLY: NEVER is equally the fallback for
 *   every non-Amount/CostPrice/Quantity widget whose AD_UI_Element.ViewEditMode is null
 *   (LayoutFactory.java:600-617). On this layout every element of group 540617 has ViewEditMode
 *   NULL and DocumentType is a List widget, so both read "never" — a read-only field and an
 *   editable one collapse onto the same value and the property cannot discriminate between them.
 *   (C)+(D) therefore prove exactly the user-visible outcome AC1 asks for — on this window the
 *   resolved doctype can be seen but not edited — and nothing about the AD_Field configuration
 *   behind it.
 *
 * WHY the doctype identity is asserted via DocBaseType and not via the widget's text:
 *   The widget only ever renders the doctype's CAPTION, which is served per AD_Language out of
 *   C_DocType_Trl — invariant today only because this doctype happens to be untranslated in every
 *   language, which a later translation would silently break (e2e/frontend-webui/CLAUDE.md § "Specs
 *   MUST be language-independent"). Worse, comparing the widget against the same field of the same
 *   payload only proves the widget renders what the API returned. So the primary assertion is the
 *   language-invariant identity (value.key -> DocBaseType code), and the caption equality is kept
 *   only as a secondary "the widget shows THAT doctype" check.
 *
 * ---------------------------------------------------------------------------------------------------
 * HOW THE RECORDS UNDER TEST COME INTO EXISTENCE — and why the spec must provision them
 * ---------------------------------------------------------------------------------------------------
 * On a CLEAN seed database — which is what core CI runs the suite against — C_Order_MFGWarehouse_Report
 * is EMPTY: migration 5825550 backfills C_DocType_ID on rows that already exist and creates none, and the
 * sysconfig that would make a completing sales order generate reports by itself
 * (de.metas.fresh.ordercheckup.CreateAndRouteJasperReports.OnSalesOrderComplete, read in
 * OrderCheckupBL.isGenerateReportsOnOrderComplete) ships as 'N'. A spec that only READ the window's view
 * therefore cannot work on CI, however well it works against a data-rich customer stack. So the spec
 * provisions its own records, through the existing /api/v2/frontendTesting masterdata surface
 * (e2e/CLAUDE.md § "Test data only via the Backend masterdata API") plus AD_Process 540603
 * (C_Order_MFGWarehouse_Report_Generate), which calls OrderCheckupBL.generateReportsIfEligible directly
 * (C_Order_MFGWarehouse_Report_Generate.java:60) — the same method the on-complete path calls.
 *
 * DRIVING THAT PROCESS IS A DELIBERATE CHOICE over flipping the OnSalesOrderComplete sysconfig: the
 * sysconfig is a client-0/org-0 system-level write, so every sales order ANY concurrently-running spec
 * completes would start generating checkup reports too, while the process touches only the one order it is
 * invoked on. Why the REST invocation works although the process's gear-menu precondition sysconfig
 * (…CreateAndRouteJasperReports.EnableProcessGear) is seeded 'N': the REST create-instance path does not
 * consult preconditions.
 *
 * WHICH KINDS THIS YIELDS — both, deliberately, so the per-kind mapping assertion keeps its full meaning:
 *   * Warehouse('WH') — needs the ORDER LINE's product to have a manufacturing PP_Product_Planning WITH a
 *     workflow (OrderCheckupBL.java:138-183). CreateProductPlanningCommand.java:37-46 sets IsManufactured
 *     plus the default routing only when a `bom` (or `pickingOrder`) is given, hence the BOM on the
 *     manufactured product.
 *   * Plant('PL') — needs the ORDER's warehouse to carry a plant (OrderCheckupBL.java:191-217); no product
 *     planning is involved. Hence the seed warehouse below, which has one.
 */

