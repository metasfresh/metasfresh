/** Flatten a window-layout element group to its ordered list of ColumnNames. */
function groupFieldNames(group) {
  const names = [];
  for (const line of group.elementsLine || []) {
    for (const el of line.elements || []) {
      for (const f of el.fields || []) {
        if (f.field) names.push(f.field);
      }
    }
  }
  return names;
}

/** Unwrap the single-document GET payload, which may be an array or a {documents:[…]} envelope. */
function singleDocumentOf(body) {
  return Array.isArray(body) ? body[0] : (body.documents || [body])[0];
}

